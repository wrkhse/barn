#!/usr/bin/env node
import { spawnSync } from "node:child_process"
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const DEFAULT_TARGET = path.join(ROOT, ".vendor", "sourcefed")
const REPOSITORY = "https://github.com/wrkhse/sourcefed"
const TAG = "v0.5.2"
const COMMIT = "e6c1ad422fbbf86cd59d2f0a96feeb0b93ab15fb"

const LIMITER = path.join("providers", "github", "src", "api", "github-limiter.ts")
// The limiter is matching policy that would move to barn's broker budgets, so the vendored
// copy lifts it to measure the runtime rather than the limiter's queueing. Both the default
// and the ceiling go up: leaving the default at 30 would keep deferring almost every poll.
const LIFT = [
  {
    from: "const DEFAULT_REQUESTS_PER_MINUTE = 30",
    to: [
      "// The stall spike lifts this limiter: it is a matching policy that would move to barn's",
      "// broker budgets, so it is lifted here to measure the runtime itself.",
      "const DEFAULT_REQUESTS_PER_MINUTE = 1_000_000",
    ].join("\n"),
  },
  {
    from: "export const MAX_REQUESTS_PER_MINUTE = 75",
    to: "export const MAX_REQUESTS_PER_MINUTE = 1_000_000",
  },
]

const SPIKE_FILES = ["stall-a.mjs", "broker-fetch.mjs", "lane.mjs"]
const BUILT = [
  "packages/core/dist/index.js",
  "packages/daemon/dist/index.js",
  "providers/github/dist/index.js",
  "providers/jira/dist/index.js",
]

const target = path.resolve(process.argv[2] ?? DEFAULT_TARGET)

try {
  main()
} catch (error) {
  console.error(`[vendor] ${messageOf(error)}`)
  process.exitCode = 1
}

function main() {
  if (commitAt(target) !== COMMIT) {
    clone()
  }

  const patched = liftLimiter()
  if (patched || !dependenciesReady()) run("npm", ["ci"], "npm ci")
  if (patched || !buildReady()) run("node", ["scripts/build.mjs"], "node scripts/build.mjs")

  copySpike()

  console.log(JSON.stringify({ stallA: path.join(target, ".spike", "stall-a.mjs"), version: describe() }))
}

function clone() {
  console.error(`[vendor] cloning ${REPOSITORY} at ${TAG} into ${target}`)
  // A partial or moved clone is rebuilt rather than repaired; .vendor is regenerated by design.
  rmSync(target, { recursive: true, force: true })
  mkdirSync(path.dirname(target), { recursive: true })
  run("git", ["clone", "--depth", "1", "--branch", TAG, REPOSITORY, target], "git clone", ROOT)

  const commit = commitAt(target)
  if (commit !== COMMIT) {
    throw new Error(`${TAG} is at ${commit ?? "no commit"}, expected ${COMMIT}`)
  }
}

function liftLimiter() {
  const file = path.join(target, LIMITER)
  const source = readFileSync(file, "utf8")
  let patched = source
  let changed = false

  for (const { from, to } of LIFT) {
    if (patched.includes(to)) continue
    const count = patched.split(from).length - 1
    if (count !== 1) {
      throw new Error(`${LIMITER} does not contain the anchor ${JSON.stringify(from)} exactly once; the pinned source changed under the spike`)
    }
    patched = patched.replace(from, to)
    changed = true
  }

  if (changed) {
    writeFileSync(file, patched)
    console.error(`[vendor] lifted the GitHub request limiter in ${LIMITER}`)
  }
  return changed
}

function copySpike() {
  const destination = path.join(target, ".spike")
  mkdirSync(destination, { recursive: true })
  for (const file of SPIKE_FILES) {
    const source = path.join(ROOT, "ts", file)
    if (!existsSync(source)) throw new Error(`missing ${source}`)
    copyFileSync(source, path.join(destination, file))
  }
}

function dependenciesReady() {
  return ["node_modules/@sourcefed/core/package.json", "node_modules/valibot/package.json"].every((file) => existsSync(path.join(target, file)))
}

function buildReady() {
  return BUILT.every((file) => existsSync(path.join(target, file)))
}

function commitAt(directory) {
  if (!existsSync(path.join(directory, ".git"))) return undefined
  const result = spawnSync("git", ["-C", directory, "rev-parse", "HEAD"], { encoding: "utf8" })
  return result.status === 0 ? result.stdout.trim() : undefined
}

function describe() {
  const result = spawnSync("git", ["-C", target, "describe", "--tags", "--always"], { encoding: "utf8" })
  return result.status === 0 ? result.stdout.trim() : "unknown"
}

// stdout is reserved for the single JSON line; a child's stdout is redirected to stderr so
// npm and esbuild output cannot corrupt it.
function run(command, args, label, cwd = target) {
  console.error(`[vendor] ${label}`)
  const result = spawnSync(command, args, { cwd, stdio: ["ignore", 2, 2] })
  if (result.error) throw new Error(`${label} could not start: ${messageOf(result.error)}`)
  if (result.status !== 0) throw new Error(`${label} exited with ${result.status ?? result.signal}`)
}

function messageOf(error) {
  return error instanceof Error ? error.message : String(error)
}
